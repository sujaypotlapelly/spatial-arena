#!/usr/bin/env node
// Generate (or check) the missions v2 sets: search with an assigned sector,
// and delivery with an explicit release (sim/src/gym/mission_v2.js). Writes
// sim/scenarios/mission-v2-<map>-<task>.json once; later runs regenerate and
// must match, so a set can never change silently. Train and dev only: no
// test set is built.
//   node sim/tools/mission_sets_v2.mjs                 # factory, both tasks
//   node sim/tools/mission_sets_v2.mjs --task search
import fs from "node:fs";
import path from "node:path";
import { RescueMission } from "../src/gym/rescue_tasks.js";
import { makeSearchSetsV2, makeDeliverySetsV2 } from "../src/gym/mission_v2.js";
import { loadEnvironment, root } from "./benchmark_env.mjs";

export const CONFIG_V2 = {
  factory: {
    search: { idPrefix: "factory-v2-search-", seed: 20261119, windBase: 1900000, train: 12, dev: 24, sector: 24, margin: 4, detectionRange: 5, timeLimitSeconds: 90, minTargetDist: 8 },
    delivery: { idPrefix: "factory-v2-delivery-", seed: 20261129, windBase: 1910000, train: 12, dev: 24, timeLimitSeconds: 90, minDist: 15, maxDist: 35,
      padRadius: 0.5, maxReleaseHeight: 2, parcelRadius: 0.1, gravity: 9.81, landingHeightTolerance: 0.2 },
  },
};

export const fileV2 = (map, task) => path.join(root, `sim/scenarios/mission-v2-${map}-${task}.json`);

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const opt = (k, d = null) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
  const map = opt("--map", "factory");
  const E = loadEnvironment(map);
  for (const task of opt("--task") ? [opt("--task")] : ["search", "delivery"]) {
    const cfg = CONFIG_V2[map]?.[task];
    if (!cfg) throw new Error(`no v2 config for ${map} ${task}`);
    const t0 = Date.now();
    const sets = task === "search" ? makeSearchSetsV2(E.world, cfg) : makeDeliverySetsV2(E.world, cfg);
    for (const k of ["train", "dev"]) for (const m of sets[k]) new RescueMission(E.world, m, m.seeds[0]);
    const file = fileV2(map, task);
    const body = { note: `missions v2 ${task} on ${E.map}, generated by sim/tools/mission_sets_v2.mjs (sim/src/gym/mission_v2.js) with ${JSON.stringify(cfg)}. Train and dev only; each target location appears once.`, config: cfg, ...sets };
    if (!fs.existsSync(file)) fs.writeFileSync(file, JSON.stringify(body, null, 1));
    else {
      const pinned = JSON.parse(fs.readFileSync(file, "utf8"));
      for (const k of ["train", "dev"]) if (JSON.stringify(pinned[k]) !== JSON.stringify(sets[k])) throw new Error(`${path.relative(root, file)} ${k} differs from generation`);
    }
    console.log(`${map} v2 ${task}: ${sets.train.length}/${sets.dev.length} train/dev; ${JSON.stringify(sets.stats)} [${Math.round((Date.now() - t0) / 1000)} s] -> ${path.relative(root, file)}`);
  }
}
