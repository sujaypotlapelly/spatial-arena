// Builds and pins the bird scenario sets for Reach on the factory map:
// sim/scenarios/reach-bird-factory.json (train and dev only; there is no
// bird test set and this tool never reads one).
//   node sim/tools/reach_bird_scenarios.mjs            write the file (or check it if present)
//   node sim/tools/reach_bird_scenarios.mjs --rebuild  regenerate and overwrite
// Admission, per candidate bird, on both of the route's wind seeds:
//   1. meets the route: the map-and-A* planner flying BLIND to the bird is
//      caught on at least one seed and comes within NEAR_M of the bird on both;
//   2. solvable: the same planner with a simple keep-away reaches the goal on
//      both seeds, at one of six fixed settings (cruise speed 3.5, 4.5 or
//      5.2 m/s; keep-away radius 7 or 10 m).
// Both planners are privileged (plannerKeepAway in reach_bird_agents.js) and
// are used for admission only.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { World } from "../src/world.js";
import { runEpisode } from "../src/gym/core.js";
import { ReachBird, makeBirdSets } from "../src/gym/reach_bird.js";
import { plannerKeepAway } from "../src/gym/reach_bird_agents.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "../..");
export const BIRD_SCENARIO_FILE = path.join(root, "sim/scenarios/reach-bird-factory.json");
export const NEAR_M = 2.5;

export function loadFactory() {
  const world = new World(JSON.parse(fs.readFileSync(path.join(root, "sim/maps/factory-full.json"))));
  const pinned = JSON.parse(fs.readFileSync(path.join(root, "sim/scenarios/reach-factory.json")));
  // Only train and dev are ever read.
  return { world, routes: { train: pinned.train, dev: pinned.dev } };
}

export const admitWith = (world) => async (sc) => {
  const blind = [], aware = [];
  for (const seed of sc.seeds) {
    const b = (await runEpisode(new ReachBird(world, sc, seed), plannerKeepAway(world, sc, { keepAway: false }))).result;
    blind.push(b);
    if (b.minBirdDist > NEAR_M) return null;
  }
  if (!blind.some((r) => r.outcome === "caught")) return null;
  // Solvable: some keep-away setting (cruise speed, avoidance radius) reaches
  // the goal on both seeds. The first that does is recorded as the witness.
  for (const setting of KEEPAWAY_SETTINGS) {
    aware.length = 0;
    for (const seed of sc.seeds) {
      const a = (await runEpisode(new ReachBird(world, sc, seed), plannerKeepAway(world, sc, setting))).result;
      if (a.outcome !== "reached") break;
      aware.push(a);
    }
    if (aware.length === sc.seeds.length)
      return {
        blind_planner: blind.map((r) => ({ outcome: r.outcome, time: r.time, minBirdDist: r.minBirdDist })),
        keepaway_planner: { setting, flights: aware.map((r) => ({ outcome: r.outcome, time: r.time, minBirdDist: r.minBirdDist })) },
      };
  }
  return null;
};
export const KEEPAWAY_SETTINGS = [3.5, 4.5, 5.2].flatMap((speed) => [7, 10].map((avoid) => ({ speed, avoid })));

// Practice (train) set, version 2 (2026-11-19): with one bird per route the
// train set was much harder than dev (the frozen published program reached
// 4/20 on train against 15/38 on dev), which left a practice loop almost no
// successes to learn from. Version 2 keeps the same candidate order and
// admission rule but keeps the first THREE admitted birds per train route,
// and adds every train route once with the bird absent (obs.bird always reads
// not visible), so successes exist and hovering earns nothing. Dev keeps one
// bird per route, unchanged. train_v1 is the earlier train set, kept so the
// first practice run (runs/reach-bird/cap1) stays reproducible.
export const TRAIN_BIRDS_PER_ROUTE = 3;
export async function buildBirdSets() {
  const { world, routes } = loadFactory();
  const sets = await makeBirdSets(world, routes, admitWith(world), { perRoute: { train: TRAIN_BIRDS_PER_ROUTE, dev: 1 } });
  const absent = routes.train.map((r) => ({ ...r, id: `${r.id}-nobird`, bird: { strategy: "absent" } }));
  const train_v1 = sets.train.filter((s) => routes.train.some((r) => r.id === s.id));
  return {
    note: "Bird scenarios for Reach on the factory map (train and dev only; no test set). Generated by sim/tools/reach_bird_scenarios.mjs: scripted birds on Reach routes, each admitted only if the map-and-A* planner flying blind to the bird is caught on at least one wind seed (and comes within 2.5 m on both) and the same planner with a simple keep-away (one of six fixed speed and radius settings) reaches the goal on both seeds. dev: the first admitted bird per route. train (practice set v2): the first three admitted birds per train route, plus every train route once with the bird absent (ids ending -nobird). train_v1: the first admitted bird per train route (the earlier practice set). Routes with no admitted bird are listed under rejected.",
    train: [...sets.train, ...absent],
    dev: sets.dev,
    train_v1,
    rejected: sets.rejected,
  };
}

export function loadBirdSets() {
  return JSON.parse(fs.readFileSync(BIRD_SCENARIO_FILE, "utf8"));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const body = await buildBirdSets();
  const text = JSON.stringify(body, null, 1);
  const count = (k) => Object.entries(Object.groupBy(body[k], (s) => s.bird.strategy)).map(([s, xs]) => `${s} ${xs.length}`).join(", ");
  console.log(`train ${body.train.length} (${count("train")}); dev ${body.dev.length} (${count("dev")}); rejected ${body.rejected.map((r) => r.id).join(", ") || "none"}`);
  if (!fs.existsSync(BIRD_SCENARIO_FILE) || process.argv.includes("--rebuild")) {
    fs.writeFileSync(BIRD_SCENARIO_FILE, text);
    console.log("wrote", path.relative(root, BIRD_SCENARIO_FILE));
  } else if (fs.readFileSync(BIRD_SCENARIO_FILE, "utf8") !== text) {
    console.error("sim/scenarios/reach-bird-factory.json differs from what the generator produces now");
    process.exit(1);
  } else console.log("pinned file matches");
}
