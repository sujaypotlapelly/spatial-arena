#!/usr/bin/env node
// Generate (or check) the search and delivery mission sets for benchmark
// environments. Writes sim/scenarios/mission-<map>-<task>.json once; later
// runs regenerate and must match, so a set can never change silently.
//   node sim/tools/maps/make_mission_sets.mjs                 # all maps, both tasks
//   node sim/tools/maps/make_mission_sets.mjs --map canyon --task search
import fs from "node:fs";
import path from "node:path";
import { RescueMission } from "../../src/gym/rescue_tasks.js";
import { makeMissionSets } from "../../src/gym/mission_sets.js";
import { ENVIRONMENTS, loadEnvironment, missionSpotFilter, root } from "../benchmark_env.mjs";

const args = process.argv.slice(2);
const opt = (k, d = null) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const maps = opt("--map") ? [opt("--map")] : Object.keys(ENVIRONMENTS).filter((k) => ENVIRONMENTS[k].missions);

export function missionFile(map, task) { return path.join(root, `sim/scenarios/mission-${map}-${task}.json`); }

for (const map of maps) {
  const E = loadEnvironment(map);
  for (const task of opt("--task") ? [opt("--task")] : Object.keys(E.missions)) {
    const cfg = { idPrefix: `${map}-${task}-`, ...E.missions[task] };
    const t0 = Date.now();
    const sets = makeMissionSets(E.world, task, cfg, { spotFilter: missionSpotFilter(cfg) });
    // Every mission must construct (start clear, target hidden / hover clear).
    for (const k of ["train", "dev", "test"]) for (const m of sets[k]) new RescueMission(E.world, m, m.seeds[0]);
    const file = missionFile(map, task);
    const body = { note: `${task} missions on ${E.map}, generated by sim/tools/maps/make_mission_sets.mjs (makeMissionSets in sim/src/gym/mission_sets.js) with ${JSON.stringify(cfg)}. Each target location appears once.`, config: cfg, ...sets };
    if (!fs.existsSync(file)) fs.writeFileSync(file, JSON.stringify(body, null, 1));
    else {
      const pinned = JSON.parse(fs.readFileSync(file, "utf8"));
      for (const k of ["train", "dev", "test"]) if (JSON.stringify(pinned[k]) !== JSON.stringify(sets[k])) throw new Error(`${path.relative(root, file)} ${k} differs from generation`);
    }
    const d = sets.test.map((m) => m.straight_m);
    console.log(`${map} ${task}: ${sets.train.length}/${sets.dev.length}/${sets.test.length} missions, test straight ${Math.min(...d)}-${Math.max(...d)}; ${JSON.stringify(sets.stats)} [${Math.round((Date.now() - t0) / 1000)} s] -> ${path.relative(root, file)}`);
  }
}
