// Baseline evaluation for E1 Gate Run and E3 Fog Search.
// Runs only the non-LLM baselines: it never imports the Ripple client and
// makes no network calls.
//   node sim/tools/study/gym_baselines.mjs --env gate --set dev --seeds 2
//   node sim/tools/study/gym_baselines.mjs --env fog  --set dev --seeds 2 [--full]
// --full (fog): fly the whole time limit instead of stopping at the third
// beacon, so explored % compares like for like.
// Every episode is re-flown from its recorded commands and must reproduce.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { World } from "../../src/world.js";
import { runEpisode, replayEpisode } from "../../src/gym/core.js";
import { GateRun, makeGateSets } from "../../src/gym/gate.js";
import { astarGate, waypointGate, straightGate, reactiveGate } from "../../src/gym/gate_agents.js";
import { FogSearch, makeFogSets } from "../../src/gym/fog.js";
import { frontierFog, randomWalkFog } from "../../src/gym/fog_agents.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "../../..");
const args = process.argv.slice(2);
const opt = (k, d = null) => (args.includes(k) ? args[args.indexOf(k) + 1] : d);
const envName = opt("--env", "gate");
const setName = opt("--set", "dev");
const nSeeds = Number(opt("--seeds", 2));
const full = args.includes("--full");

const world = new World(JSON.parse(fs.readFileSync(path.join(here, "../../maps/factory-full.json"))));
const ENVS = {
  gate: {
    make: makeGateSets,
    file: "gate-factory.json",
    note: "Gate Run courses (factory scan). Generated by makeGateSets in sim/src/gym/gate.js; the evaluator regenerates and checks them.",
    Env: GateRun,
    conditions: [
      { key: "astar@C2 (map, 4 Hz)", level: "C2", ctl: astarGate, dt: 0.25 },
      { key: "astar@C2 (map, 1 Hz)", level: "C2", ctl: astarGate, dt: 1 },
      { key: "waypoint@C1 (map, 1 Hz)", level: "C1", ctl: waypointGate, dt: 1 },
      { key: "reactive@C3 (senses, 1 Hz)", level: "C3", ctl: reactiveGate, dt: 1 },
      { key: "straight@C2 (senses, 1 Hz)", level: "C2", ctl: straightGate, dt: 1 },
    ],
  },
  fog: {
    make: makeFogSets,
    file: "fog-factory.json",
    note: "Fog Search scenarios (factory scan). Generated by makeFogSets in sim/src/gym/fog.js; the evaluator regenerates and checks them.",
    Env: FogSearch,
    conditions: [
      { key: "frontier@C2 (own sensor map, 1 Hz)", level: "C2", ctl: frontierFog, dt: 1 },
      { key: "random walk@C3 (senses, 1 Hz)", level: "C3", ctl: randomWalkFog, dt: 1 },
    ],
  },
};
const E = ENVS[envName];
if (!E) throw new Error(`unknown --env ${envName}`);
const sets = E.make(world);
const setsFile = path.join(here, "../../scenarios", E.file);
if (!fs.existsSync(setsFile)) fs.writeFileSync(setsFile, JSON.stringify({ note: E.note, ...sets }, null, 1));
else if (JSON.stringify(JSON.parse(fs.readFileSync(setsFile)).dev) !== JSON.stringify(sets.dev)) throw new Error(`${E.file} differs from the generator output`);
const scenarios = sets[setName];
const outDir = path.resolve(opt("--out", path.join(root, "runs/gym", `${envName}-${setName}-${new Date().toISOString().replace(/[:.]/g, "-")}`)));
fs.mkdirSync(outDir, { recursive: true });

const rows = [];
let replayed = 0, mismatched = 0;
for (const c of E.conditions) {
  for (const sc of scenarios) {
    for (const seed of sc.seeds.slice(0, nSeeds)) {
      const mk = () => new E.Env(world, sc, seed, c.level, envName === "fog" ? { stopWhenFound: !full } : undefined);
      const ep = await runEpisode(mk(), c.ctl(world, sc, { seed }), { dt: c.dt });
      const re = replayEpisode(mk(), ep.decisions, { dt: c.dt });
      replayed++;
      if (JSON.stringify(re) !== JSON.stringify(ep.result)) mismatched++;
      rows.push({ condition: c.key, scenario: sc.id, seed, ...ep.result, decisions: ep.decisions.length });
    }
  }
}
fs.writeFileSync(path.join(outDir, "episodes.json"), JSON.stringify({ env: envName, set: setName, seeds: nSeeds, full, rows }, null, 1));

const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : NaN);
const median = (xs) => {
  if (!xs.length) return NaN;
  const s = [...xs].sort((a, b) => a - b);
  return s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2;
};
const f1 = (x) => (Number.isFinite(x) ? x.toFixed(1) : "—");
const lines = [`# ${envName === "gate" ? "E1 Gate Run" : "E3 Fog Search"} baselines: ${setName} set, ${scenarios.length} scenarios × ${nSeeds} seeds${full ? ", full time limit" : ""}`, "", `Replays exact: ${replayed - mismatched}/${replayed}`, ""];
if (envName === "gate") {
  lines.push("| Baseline | Laps finished | Clean laps | Median lap (s) | Mean lap (s) | Gates missed / lap | Wall contacts / lap |", "|---|---|---|---|---|---|---|");
  for (const c of E.conditions) {
    const R = rows.filter((r) => r.condition === c.key);
    const laps = R.filter((r) => r.lapTime !== null).map((r) => r.lapTime);
    lines.push(`| ${c.key} | ${laps.length}/${R.length} | ${R.filter((r) => r.clean).length}/${R.length} | ${f1(median(laps))} | ${f1(mean(laps))} | ${f1(mean(R.map((r) => r.gatesMissed)))} | ${f1(mean(R.map((r) => r.contacts)))} |`);
  }
} else {
  lines.push("| Baseline | Found all 3 | Beacons found / run | Median time to all 3 (s) | Explored @60 s | Explored @180 s or end | Wall contacts / run | Revisits / run |", "|---|---|---|---|---|---|---|---|");
  for (const c of E.conditions) {
    const R = rows.filter((r) => r.condition === c.key);
    const t = R.filter((r) => r.timeToFindAll !== null).map((r) => r.timeToFindAll);
    const at60 = R.map((r) => (r.coverage.find((x) => x[0] === 60) || [0, r.exploredPct])[1]);
    lines.push(`| ${c.key} | ${t.length}/${R.length} | ${f1(mean(R.map((r) => r.beaconsFound)))} | ${f1(median(t))} | ${f1(mean(at60))}% | ${f1(mean(R.map((r) => r.exploredPct)))}% | ${f1(mean(R.map((r) => r.contacts)))} | ${f1(mean(R.map((r) => r.revisits)))} |`);
  }
}
const md = lines.join("\n");
fs.writeFileSync(path.join(outDir, "summary.md"), md + "\n");
console.log(md);
console.log(`\n${outDir}`);
if (mismatched) process.exit(1);
