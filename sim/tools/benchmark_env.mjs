// Shared loader for benchmark environments (sim/scenes/benchmark-sets.json):
// the map, its reach route sets, and the scene text for prompts. Tools take
// --map <name>; "factory" reproduces the methodology v3 sets exactly.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { World } from "../src/world.js";
import { makeReachSets } from "../src/gym/reach.js";

const here = path.dirname(fileURLToPath(import.meta.url));
export const root = path.join(here, "../..");
export const ENVIRONMENTS = JSON.parse(fs.readFileSync(path.join(root, "sim/scenes/benchmark-sets.json"), "utf8")).environments;

// Missions whose config names a targetMask (written by
// sim/tools/env/suggest_volume.mjs) may only place targets where the mask is 1:
// ground the scan captured. Returns undefined when the config has none.
export function missionSpotFilter(cfg) {
  if (!cfg?.targetMask) return undefined;
  const M = JSON.parse(fs.readFileSync(path.join(root, cfg.targetMask), "utf8"));
  const [NX, NZ] = M.dims;
  const mask = new Uint8Array(NX * NZ);
  { let i = 0, val = M.firstValue; for (const n of M.runs) { if (val) mask.fill(1, i, i + n); i += n; val = val ? 0 : 1; } }
  return (p) => {
    const ix = Math.floor((p[0] - M.origin[0]) / M.cell), iz = Math.floor((p[2] - M.origin[1]) / M.cell);
    return ix >= 0 && iz >= 0 && ix < NX && iz < NZ && mask[ix + NX * iz] === 1;
  };
}

export function loadEnvironment(name) {
  const env = ENVIRONMENTS[name];
  if (!env) throw new Error(`--map must be one of ${Object.keys(ENVIRONMENTS).join(", ")}`);
  const mapFile = path.join(root, env.map);
  if (!fs.existsSync(mapFile)) throw new Error(`${env.map} is missing; build it with sim/tools/maps/build_splat_map.mjs --scene ${name}`);
  const world = new World(JSON.parse(fs.readFileSync(mapFile, "utf8")));
  const sets = makeReachSets(world, env.reach);
  return { name, ...env, world, sets };
}

// Dev routes for an environment whose pinned sets have none (the second
// building lists only its 40 test routes). Drawn by the same rule with a
// different seed and id prefix, skipping every start/goal pair used by any
// pinned set in either direction, so no test route is ever flown. Used only by
// the transfer study (sim/tools/transfer_matrix.mjs); returns E.sets.dev
// unchanged when it is not empty.
export function devRoutes(e, n = 24) {
  if (e.sets.dev.length) return e.sets.dev;
  const pinned = new Set(["train", "dev", "heldout", "test"].flatMap((k) => e.sets[k] ?? []).map((s) => [s.start, s.goal].sort().join("|")));
  const pool = makeReachSets(e.world, { ...e.reach, train: 0, dev: 0, heldout: 0, test: pinned.size + n + 40, seed: 20261119, idPrefix: `${e.name}-tdev-`, windOffset: 950000 }).test;
  return pool.filter((s) => !pinned.has([s.start, s.goal].sort().join("|"))).slice(0, n).map((s, i) => ({ ...s, id: `${e.name}-tdev-D${i + 1}` }));
}

// Write the scenario file once; afterwards check that generation still
// matches it, so a changed map or generator can never silently change a set.
export function pinScenarios(e) {
  if (!e.scenarioFile) return;
  const file = path.join(root, e.scenarioFile);
  const body = { note: `Reach scenario sets (${e.name}). Generated by makeReachSets in sim/src/gym/reach.js from ${e.map} with ${JSON.stringify(e.reach)}; tools regenerate and check them.`, ...e.sets };
  if (!fs.existsSync(file)) { fs.writeFileSync(file, JSON.stringify(body, null, 1)); return; }
  const pinned = JSON.parse(fs.readFileSync(file, "utf8"));
  // The factory file predates the v3 test set, so only the sets it lists are checked.
  for (const k of ["train", "dev", "heldout", "test"]) {
    if (k in pinned && JSON.stringify(pinned[k]) !== JSON.stringify(e.sets[k])) throw new Error(`${e.scenarioFile} ${k} differs from makeReachSets output`);
  }
}
