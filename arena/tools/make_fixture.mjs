// Writes arena/fixtures/determinism.json: flights produced by the benchmark's
// own Node code path (sim/src controllers, sim/src/gym/policy_sandbox.js for
// programs), which the arena's code path must reproduce in Node
// (arena/test/determinism.test.mjs) and in the browser (the page's
// "Check this browser" button).
//
//   node arena/tools/make_fixture.mjs [--runs /path/to/main/checkout/runs]
//
// --runs also copies a few published benchmark episodes (git-ignored run
// files) into the fixture, so the test can check that the arena re-flies the
// published numbers, not only its own.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { Reach } from "../../sim/src/gym/reach.js";
import { runEpisode } from "../../sim/src/gym/core.js";
import { straightReach, reactiveReach } from "../../sim/src/gym/reach_agents.js";
import { programController, separateRandomSeed } from "../../sim/src/gym/policy_sandbox.js";
import { makeWorld, fingerprint, MAP_PATH, SCENARIO_PATH } from "../runner.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "../..");
const args = process.argv.slice(2);
const runsDir = args.includes("--runs") ? args[args.indexOf("--runs") + 1] : null;

const world = makeWorld(JSON.parse(fs.readFileSync(path.join(root, MAP_PATH), "utf8")));
const sets = JSON.parse(fs.readFileSync(path.join(root, SCENARIO_PATH), "utf8"));
const route = (id) => [...sets.train, ...sets.dev, ...sets.heldout].find((s) => s.id === id);
const ripple = fs.readFileSync(path.join(root, "arena/programs/ripple-cap2-run3-v7.js"), "utf8");
// A test-only program that leans on Math.random, so the fixture pins the
// seeded generator too.
const JITTER = `function policy(obs, memory) {
  memory.n = (memory.n || 0) + 1;
  const g = obs.goal.position, p = obs.position;
  const a = Math.atan2(g[2] - p[2], g[0] - p[0]) + (Math.random() - 0.5) * 1.2;
  return { velocity: [3 * Math.cos(a), (g[1] - p[1]) * 0.5, 3 * Math.sin(a)], say: "step " + memory.n };
}`;

const REF = {
  straight: { level: "C2", make: (sc) => straightReach(world, sc) },
  reactive: { level: "C3", make: (sc) => reactiveReach(world, sc) },
  "ripple-v7": { level: "C3", make: (sc, seed) => programController(ripple, { seed, randomSeed: separateRandomSeed(seed) }) },
  jitter: { level: "C3", make: (sc, seed) => programController(JITTER, { seed, randomSeed: separateRandomSeed(seed) }) },
};

const CASES = [
  ["D1", 0, "straight"], ["D1", 0, "reactive"], ["D1", 0, "ripple-v7"],
  ["D2", 1, "reactive"], ["D2", 1, "ripple-v7"],
  ["D5", 0, "straight"], ["D5", 0, "ripple-v7"], ["D5", 0, "jitter"],
  ["D9", 0, "reactive"], ["D9", 0, "ripple-v7"],
  ["T1", 1, "ripple-v7"], ["T1", 1, "jitter"],
];

const summarise = (sc, seed, ctl, level, ep, contacts) => ({
  route: sc.id, seed, controller: ctl, level,
  result: ep.result,
  commands: ep.decisions.map((d) => d.command),
  frames: fingerprint(ep.frames),
  contacts: fingerprint(contacts),
});

const cases = [];
for (const [id, k, ctl] of CASES) {
  const sc = route(id);
  const seed = sc.seeds[k];
  const env = new Reach(world, sc, seed, REF[ctl].level);
  const ep = await runEpisode(env, REF[ctl].make(sc, seed));
  cases.push(summarise(sc, seed, ctl, REF[ctl].level, ep, env.drone.contacts));
}

const out = {
  note: "Generated by arena/tools/make_fixture.mjs with the benchmark's Node controllers (programs through sim/src/gym/policy_sandbox.js, Math.random seeded by separateRandomSeed). The arena must reproduce every case exactly, in Node and in the browser.",
  map: MAP_PATH,
  jitterProgram: JITTER,
  cases,
};

if (runsDir) {
  // Published episodes: commands and results as the benchmark recorded them.
  const pick = (dir, filter, n) => {
    const file = path.join(runsDir, dir, "episodes.jsonl");
    const rows = fs.readFileSync(file, "utf8").trim().split("\n").map((l) => JSON.parse(l)).filter(filter).slice(0, n);
    return rows.map((e) => ({
      source: `runs/reach/${dir}/episodes.jsonl`,
      route: e.scenario, seed: e.seed, controller: e.ctl === "program" ? "ripple-v7" : e.ctl, level: e.level,
      result: e.result,
      commands: e.decisionLog.map((d) => d.command),
      frames: fingerprint(e.frames),
    }));
  };
  out.published = [
    ...pick("baselines-dev", (e) => e.ctl === "straight", 3),
    ...pick("baselines-dev", (e) => e.ctl === "reactive", 3),
    ...pick("heldout6-cap2-run3", (e) => e.seed === route(e.scenario).seeds[0] || e.seed === route(e.scenario).seeds[1], 4),
  ];
}

fs.writeFileSync(path.join(root, "arena/fixtures/determinism.json"), JSON.stringify(out, null, 0).replace(/\{"route"/g, '\n{"route"').replace(/\{"source"/g, '\n{"source"') + "\n");
console.log(`${cases.length} cases${out.published ? `, ${out.published.length} published episodes` : ""}`);
