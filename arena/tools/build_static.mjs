// Builds a self-contained static folder for the arena page.
//
//   node arena/tools/build_static.mjs [out-dir]     (default: arena/dist)
//
// The page imports the simulator from ../sim/src/ and fetches the map and the
// route sets from ../sim/, so a deploy needs those files next to arena/. This
// script follows the actual ES module imports from the page and its Web
// Worker (so a new import in sim/src is picked up, and nothing unused is
// copied), adds the data files the page fetches, and writes them into
// out-dir with the same relative layout:
//
//   out-dir/index.html            redirect to arena/
//   out-dir/arena/...             the page
//   out-dir/sim/src/...           the simulator modules it imports, unchanged
//   out-dir/sim/maps/factory-full.json
//   out-dir/sim/scenarios/reach-factory.json
//   out-dir/FILES.txt             every file with its size and sha256
//
// Host out-dir at any path; every URL in the page is relative. Copies files
// byte for byte (no bundling or minifying), so what is served is exactly the
// code the tests ran. It never deploys anything.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import zlib from "node:zlib";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, "../..");
const out = path.resolve(process.argv[2] || path.join(root, "arena/dist"));
const marker = "Arena static build. ";
if (fs.existsSync(out)) {
  if (!fs.lstatSync(out).isDirectory()) throw new Error("build output must be a directory");
  if (fs.readdirSync(out).length) {
    const manifest = path.join(out, "FILES.txt");
    if (!fs.existsSync(manifest) || !fs.readFileSync(manifest, "utf8").startsWith(marker)) {
      throw new Error("choose an empty directory or a previous arena build");
    }
  }
}
const actual = fs.existsSync(out) ? fs.realpathSync(out) : out;
const relativeRoot = path.relative(actual, root);
if (!relativeRoot || (!relativeRoot.startsWith(".." + path.sep) && relativeRoot !== "..")) {
  throw new Error("refusing to write over the repository or a parent directory");
}

// Entry modules: the page script and the worker script.
const ENTRIES = ["arena/app.js", "arena/policy_worker.js"];
// Files fetched or linked rather than imported.
const DATA = [
  "arena/index.html",
  "arena/arena.css",
  "arena/programs/ripple-cap2-run3-v7.js", // fetched as text, never imported
  "arena/programs/manifest.json", // provenance, for anyone reading the deploy
  "arena/fixtures/determinism.json", // the browser check
  "sim/maps/factory-full.json",
  "sim/scenarios/reach-factory.json",
];

const IMPORT_RE = /(?:^|[\s;])(?:import|export)\s[^'"]*?from\s*["']([^"']+)["']|(?:^|[\s;(])import\s*\(\s*["']([^"']+)["']\s*\)|^\s*import\s*["']([^"']+)["']/gm;
function importsOf(file) {
  const src = fs.readFileSync(path.join(root, file), "utf8");
  const deps = [];
  for (const m of src.matchAll(IMPORT_RE)) {
    const spec = m[1] || m[2] || m[3];
    if (!spec.startsWith(".")) throw new Error(`${file} imports "${spec}", which a static folder cannot serve`);
    deps.push(path.relative(root, path.resolve(path.dirname(path.join(root, file)), spec)));
  }
  return deps;
}

const modules = new Set();
const queue = [...ENTRIES];
while (queue.length) {
  const f = queue.shift();
  if (modules.has(f)) continue;
  modules.add(f);
  queue.push(...importsOf(f));
}

const files = [...modules, ...DATA].sort();
fs.rmSync(out, { recursive: true, force: true });
let total = 0, gz = 0;
const lines = [];
for (const f of files) {
  const buf = fs.readFileSync(path.join(root, f));
  fs.mkdirSync(path.dirname(path.join(out, f)), { recursive: true });
  fs.writeFileSync(path.join(out, f), buf);
  const g = zlib.gzipSync(buf, { level: 9 }).length;
  total += buf.length;
  gz += g;
  lines.push(`${String(buf.length).padStart(8)}  ${String(g).padStart(7)}  ${crypto.createHash("sha256").update(buf).digest("hex").slice(0, 16)}  ${f}`);
}
fs.writeFileSync(path.join(out, "index.html"), '<!doctype html><meta charset="utf-8"><meta http-equiv="refresh" content="0; url=arena/"><title>Spatial Arena</title><a href="arena/">Spatial Arena: try it yourself</a>\n');
const summary = `${files.length} files, ${(total / 1024).toFixed(1)} KB as served uncompressed, ${(gz / 1024).toFixed(1)} KB gzipped (plus index.html, a redirect to arena/).`;
fs.writeFileSync(path.join(out, "FILES.txt"), `${marker}${summary}\nGenerated by arena/tools/build_static.mjs; files are byte-identical copies from the repository.\n\n   bytes  gzipped  sha256 (16)       path\n${lines.join("\n")}\n`);
console.log(`${summary}\nWrote ${path.relative(process.cwd(), out) || out}`);
for (const l of lines) console.log(l);
